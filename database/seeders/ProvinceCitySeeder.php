<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;

/** ۳۱ استان با مرکز استان و چند شهر بزرگ؛ فهرست شهرها را بعداً با داده‌ی کامل جایگزین کن. */
class ProvinceCitySeeder extends Seeder
{
    public function run(): void
    {
        foreach ([
            ['آذربایجان شرقی', ['تبریز', 'مراغه', 'مرند']],
            ['آذربایجان غربی', ['ارومیه']],
            ['اردبیل', ['اردبیل']],
            ['اصفهان', ['اصفهان', 'کاشان', 'نجف‌آباد', 'خمینی‌شهر']],
            ['البرز', ['کرج', 'نظرآباد', 'فردیس']],
            ['ایلام', ['ایلام']],
            ['بوشهر', ['بوشهر']],
            ['تهران', ['تهران', 'ری', 'شمیرانات', 'اسلامشهر', 'پاکدشت']],
            ['چهارمحال و بختیاری', ['شهرکرد']],
            ['خراسان جنوبی', ['بیرجند']],
            ['خراسان رضوی', ['مشهد', 'نیشابور', 'سبزوار']],
            ['خراسان شمالی', ['بجنورد']],
            ['خوزستان', ['اهواز']],
            ['زنجان', ['زنجان']],
            ['سمنان', ['سمنان']],
            ['سیستان و بلوچستان', ['زاهدان']],
            ['فارس', ['شیراز', 'مرودشت', 'کازرون']],
            ['قزوین', ['قزوین']],
            ['قم', ['قم']],
            ['کردستان', ['سنندج']],
            ['کرمان', ['کرمان']],
            ['کرمانشاه', ['کرمانشاه']],
            ['کهگیلویه و بویراحمد', ['یاسوج']],
            ['گلستان', ['گرگان']],
            ['گیلان', ['رشت', 'انزلی', 'لاهیجان']],
            ['لرستان', ['خرم‌آباد']],
            ['مازندران', ['ساری', 'بابل', 'آمل']],
            ['مرکزی', ['اراک']],
            ['هرمزگان', ['بندرعباس']],
            ['همدان', ['همدان']],
            ['یزد', ['یزد']],
        ] as [$province, $cities]) {
            $id = DB::table('provinces')->where('name', $province)->value('id')
                ?? DB::table('provinces')->insertGetId(['name' => $province]);

            foreach ($cities as $city) {
                if (! DB::table('cities')->where('province_id', $id)->where('name', $city)->exists()) {
                    DB::table('cities')->insert(['province_id' => $id, 'name' => $city]);
                }
            }
        }
    }
}
