<?php

namespace App\Services\Auth;

use App\Enums\MembershipStatus;
use App\Exceptions\InvitationException;
use App\Models\Building;
use App\Models\BuildingUserRole;
use App\Models\Invitation;
use App\Models\Role;
use App\Models\User;
use App\Services\Sms\SmsSender;
use App\Support\CurrentBuilding;
use App\Support\MobileNumber;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;

/**
 * دعوت عضو یا پرسنل با پیامک (بند ۴.۸ و ۴.۹ سند).
 * invite() باید داخل context یک ساختمان (CurrentBuilding) صدا زده شود.
 */
class InvitationService
{
    public const TTL_DAYS = 7;

    public function __construct(private readonly SmsSender $sms)
    {
    }

    /** @return array{0: Invitation, 1: string} رکورد دعوت و توکن خام (فقط در پیامک می‌رود و ذخیره نمی‌شود) */
    public function invite(string $mobile, string $roleKey, User $inviter): array
    {
        $mobile = MobileNumber::normalize($mobile) ?? throw new InvitationException('شماره‌ی موبایل معتبر نیست.');
        $buildingId = app(CurrentBuilding::class)->id() ?? throw new InvitationException('ساختمان فعالی انتخاب نشده است.');
        $buildingHasRoles = Role::where('building_id', $buildingId)->where('is_staff', true)->exists();
        $role = Role::where('key', $roleKey)->where(function ($query) use ($buildingId, $roleKey, $buildingHasRoles) {
            $query->where('building_id', $buildingId);
            if (in_array($roleKey, ['owner', 'manager', 'unit_owner', 'tenant'], true) || ! $buildingHasRoles) $query->orWhereNull('building_id');
        })->where('is_active', true)->firstOr(fn () => throw new InvitationException('نقش نامعتبر است.'));

        $user = User::firstOrCreate(['mobile' => $mobile], ['status' => 'invited']);

        $membership = BuildingUserRole::where(['building_id' => $buildingId, 'user_id' => $user->id, 'role_id' => $role->id])->first();
        if ($membership?->status === MembershipStatus::Active) {
            throw new InvitationException('این شخص قبلاً با همین نقش عضو ساختمان است.');
        }

        $token = Str::random(40);

        $invitation = DB::transaction(function () use ($buildingId, $user, $role, $mobile, $inviter, $token) {
            BuildingUserRole::updateOrCreate(
                ['building_id' => $buildingId, 'user_id' => $user->id, 'role_id' => $role->id],
                ['status' => 'invited', 'invited_by' => $inviter->id, 'invited_at' => now()],
            );

            return Invitation::create([
                // Set tenant explicitly as well as relying on the model hook.
                'building_id' => $buildingId,
                'user_id' => $user->id,
                'role_id' => $role->id,
                'mobile' => $mobile,
                'token_hash' => hash('sha256', $token),
                'expires_at' => now()->addDays(self::TTL_DAYS),
                'created_by' => $inviter->id,
            ]);
        });

        $this->sms->sendTemplate('invitation', $mobile, [
            'inviter' => $inviter->display_name,
            'building' => Building::find($buildingId)->name,
            'role' => $role->name_fa,
            // Build the public link from the current request origin/base path. On XAMPP, APP_URL
            // is often left at http://localhost even when the app lives under /borjik/public;
            // that sends invitations to a different Laravel app (or a route with no invitation).
            'link' => request()->getSchemeAndHttpHost()
                .rtrim(request()->getBaseUrl(), '/')
                .route('invite.show', $token, false),
        ], $user->id, $buildingId);

        return [$invitation, $token];
    }

    /** دعوت معتبر را با توکن پیدا می‌کند (بدون نیاز به ساختمان فعال). */
    public function find(string $token): Invitation
    {
        // Invite links are public and must resolve regardless of the visitor's selected building.
        // Remove all model scopes for this one token lookup; tenant membership is checked again
        // when accepting the invitation, inside the invitation's own building context.
        // SMS clients sometimes append punctuation or encode URL characters when opening links.
        // Tokens generated by Str::random(40) are strictly alphanumeric, so normalize to that alphabet.
        $token = preg_replace('/[^A-Za-z0-9]/', '', rawurldecode(trim($token))) ?? '';
        $invitation = $token === ''
            ? null
            : Invitation::withoutGlobalScopes()
                ->where('token_hash', hash('sha256', $token))
                ->first();

        if (! $invitation) {
            Log::warning('Invitation token lookup failed.', ['reason' => 'not_found', 'token_length' => strlen($token)]);
            throw new InvitationException('لینک دعوت نامعتبر یا منقضی شده است.');
        }

        if ($invitation->accepted_at || $invitation->rejected_at) {
            Log::info('Invitation token lookup rejected.', ['reason' => $invitation->accepted_at ? 'already_accepted' : 'already_rejected', 'invitation_id' => $invitation->getKey()]);
            throw new InvitationException('این دعوت‌نامه قبلاً تعیین تکلیف شده است.');
        }

        if (! $invitation->expires_at || $invitation->expires_at->isPast()) {
            Log::info('Invitation token lookup rejected.', ['reason' => 'expired', 'invitation_id' => $invitation->getKey()]);
            throw new InvitationException('لینک دعوت نامعتبر یا منقضی شده است.');
        }

        return $invitation;
    }

    /** پذیرش با توکن پیامکی؛ رفتار قبلی حفظ می‌شود. */
    public function accept(string $token, User $user): Invitation
    {
        return $this->acceptInvitation($this->find($token), $user);
    }

    /** پذیرش یک رکورد دعوت متعلق به کاربر واردشده. */
    public function acceptInvitation(Invitation $invitation, User $user): Invitation
    {
        if ((int) $invitation->user_id !== (int) $user->id || $invitation->mobile !== $user->mobile) {
            throw new InvitationException('این دعوت برای حساب کاربری دیگری ارسال شده است.');
        }

        if ($invitation->accepted_at || $invitation->rejected_at) {
            throw new InvitationException('این دعوت‌نامه قبلاً تعیین تکلیف شده است.');
        }

        if (! $invitation->expires_at || $invitation->expires_at->isPast()) {
            throw new InvitationException('مهلت این دعوت‌نامه به پایان رسیده است.');
        }

        $buildingId = (int) $invitation->building_id;

        app(CurrentBuilding::class)->actingAs($buildingId, function () use ($invitation, $user, $buildingId) {
            DB::transaction(function () use ($invitation, $user, $buildingId) {
                $scopedInvitation = Invitation::query()
                    ->where('building_id', $buildingId)
                    ->lockForUpdate()
                    ->findOrFail($invitation->getKey());

                if ($scopedInvitation->accepted_at || $scopedInvitation->rejected_at || ! $scopedInvitation->expires_at || $scopedInvitation->expires_at->isPast()) {
                    throw new InvitationException('این دعوت‌نامه دیگر قابل پذیرش نیست.');
                }

                $scopedInvitation->forceFill(['accepted_at' => now()])->save();

                BuildingUserRole::where(['building_id' => $buildingId, 'user_id' => $user->id, 'status' => 'invited'])->get()
                    ->each(fn (BuildingUserRole $r) => $r->update(['status' => 'active', 'joined_at' => now()]));

                if ($user->status === 'invited') {
                    $user->update(['status' => 'active']);
                }
            });
        });

        return $invitation;
    }

    /** رد دعوت توسط همان کاربری که دعوت‌نامه به حسابش تعلق دارد. */
    public function reject(Invitation $invitation, User $user): void
    {
        if ((int) $invitation->user_id !== (int) $user->id || $invitation->mobile !== $user->mobile) {
            throw new InvitationException('این دعوت برای حساب کاربری دیگری ارسال شده است.');
        }

        $buildingId = (int) $invitation->building_id;

        app(CurrentBuilding::class)->actingAs($buildingId, function () use ($invitation, $user, $buildingId) {
            DB::transaction(function () use ($invitation, $user, $buildingId) {
                $scopedInvitation = Invitation::query()
                    ->where('building_id', $buildingId)
                    ->lockForUpdate()
                    ->findOrFail($invitation->getKey());

                if ($scopedInvitation->accepted_at || $scopedInvitation->rejected_at) {
                    throw new InvitationException('این دعوت‌نامه قبلاً تعیین تکلیف شده است.');
                }

                if (! $scopedInvitation->expires_at || $scopedInvitation->expires_at->isPast()) {
                    throw new InvitationException('مهلت این دعوت‌نامه به پایان رسیده است.');
                }

                $scopedInvitation->forceFill(['rejected_at' => now()])->save();

                BuildingUserRole::where([
                    'building_id' => $buildingId,
                    'user_id' => $user->id,
                    'role_id' => $scopedInvitation->role_id,
                    'status' => 'invited',
                ])->update(['status' => 'rejected']);
            });
        });
    }
}
